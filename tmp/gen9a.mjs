import fs from 'node:fs';
import path from 'node:path';
const DIR = path.resolve('docs/content/info-room/01-startup');
const UDONG = '우리 동네 공부방·과외 정보는 우동공과 카드로도 정리해 두시면 좋아요.';

function build(def) {
  let b = `# ${def.title}\n\n이 글에서 알 수 있는 것\n`;
  for (const s of def.sum) b += `- ${s}\n`;
  for (const sec of def.secs) {
    if (sec.t === 'qa') {
      b += `\n## Q&A\n`;
      for (const it of sec.items) b += `\nQ. ${it.q}  \nA. ${it.a}\n`;
    } else if (sec.t === 'cl') {
      b += `\n### 체크리스트\n`;
      for (const it of sec.items) b += `- [ ] ${it}\n`;
    } else {
      b += `\n## ${sec.h}\n`;
      for (const p of sec.p) b += `\n${p}\n`;
    }
  }
  b += `\n${UDONG}\n`;
  return b;
}
function save(fname, def, uncertain) {
  const body = build(def);
  const chars = [...body].length;
  const fm = `---\ntitle: ${def.title}\ntopic: startup\ncategory_suggest: startup\nbasis_date: 2026-11-11\nchars: ${chars}\nuncertain_facts: [${uncertain.map(u=>`"${u}"`).join(', ')}]\n---\n`;
  fs.writeFileSync(path.join(DIR, fname), fm + body, 'utf8');
  console.log('wrote', fname, chars);
}

